import { ChevronRight, Sparkles } from 'lucide-react'
import { useState } from 'react'
import type { Client, Lead } from '../data/types'
import { tailorScript } from '../lib/ai'
import { actionLabel, renderParts } from '../lib/format'
import { actionFor, segmentOf } from '../lib/segments'
import { useCurrentUser } from '../store/useStore'
import { ic } from './ui'

/** Suggested script with highlighted variables, simulated AI tailoring, and the client's objection cheat sheet. */
export default function ScriptPanel({ lead, client, compact = false }: { lead: Lead; client: Client; compact?: boolean }) {
  const me = useCurrentUser()!
  const agent = me.name.split(' ')[0]
  const [tailored, setTailored] = useState<ReturnType<typeof tailorScript> | null>(null)
  const seg = segmentOf(lead, client)
  const action = seg ? actionFor[seg] : 'finish_sale'
  const parts = tailored ? [{ t: tailored.script, v: false }] : renderParts(client.settings.scripts[action], lead, client, agent)

  return (
    <div style={{ display: 'flex', flexDirection: 'column', gap: 14 }}>
      <div style={{ display: 'flex', alignItems: 'center', gap: 8 }}>
        <span className="chip c-out">Suggested: {actionLabel[action]}</span>
        <div style={{ flex: 1 }} />
        <button className="btn btn-sm" aria-pressed={!!tailored} onClick={() => setTailored(tailored ? null : tailorScript(lead, client, agent))}>
          <Sparkles className={ic} />{tailored ? 'Standard script' : 'Tailor with AI'}
        </button>
      </div>
      <p style={{ margin: 0, fontSize: 14, lineHeight: 1.6 }}>{parts.map((p, i) => <span key={i} className={p.v ? 'var' : undefined}>{p.t}</span>)}</p>
      {tailored && (
        <ul className="muted" style={{ margin: 0, paddingLeft: 18, fontSize: 12 }}>
          {tailored.rationale.map((r) => <li key={r}>{r}</li>)}<li>Generated by simulated AI</li>
        </ul>
      )}
      {client.settings.objections.length > 0 && (
        <div>
          <div className="eyebrow" style={{ paddingBottom: 4 }}>{compact ? 'If they say…' : 'Objections'}</div>
          {client.settings.objections.map((o, i) => (
            <details key={o.id} className="obj" open={i === 0 && !compact}>
              <summary><ChevronRight className={`${ic} chev`} style={{ width: 14, height: 14 }} />“{o.q}”</summary>
              <div style={{ padding: '0 0 12px 22px', color: 'var(--text-2)', fontSize: 13 }}>{o.a}</div>
            </details>
          ))}
        </div>
      )}
    </div>
  )
}
